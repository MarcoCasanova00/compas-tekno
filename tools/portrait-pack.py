#!/usr/bin/env python3
"""Regenerate board/portrait.inc from any PNG (cross-platform port of
tools/portrait-pack.swift, which needs macOS/CoreGraphics).

The splash portrait is a 108x108, 4-bit indexed asset: 16 colors, two pixels
per byte (high nibble first), exactly like the Swift encoder. Any non-palette
color maps to the nearest of the 16 (weighted 2R^2+3G^2+B^2). By default the
current canonical palette is used; pass --palette to ship a recolorized
portrait (e.g. after a global palette change) or a fully custom one.

Usage:
  python3 tools/portrait-pack.py art.png                 # -> board/portrait.inc
  python3 tools/portrait-pack.py art.png --auto           # derive the 16-color
                                                            # palette from the art
  python3 tools/portrait-pack.py art.png -o /tmp/p.inc --palette 255,237,190 12,33,23 ...
"""
import argparse
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: pip install pillow")

SIZE = 108
DEFAULT_PALETTE = [
    (255, 237, 190), (12, 33, 23), (19, 51, 34), (28, 75, 40),
    (34, 106, 50), (69, 125, 67), (126, 19, 25), (174, 23, 28),
    (218, 32, 36), (244, 55, 48), (180, 77, 42), (214, 138, 77),
    (240, 175, 107), (254, 203, 135), (255, 222, 159), (255, 245, 213),
]

def rgb565(color):
    r, g, b = color
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def nearest_index(rgba, palette):
    r, g, b = rgba[:3]
    best, err = 0, 1 << 31
    for i, (pr, pg, pb) in enumerate(palette):
        d = 2 * (r - pr) ** 2 + 3 * (g - pg) ** 2 + (b - pb) ** 2
        if d < err:
            err, best = d, i
    return best

def pack(png: Path, palette, out: Path, auto_palette: bool = False):
    img = Image.open(png).convert("RGBA")
    # The Swift path fills the canvas with palette[0] first, then draws the
    # image stretched over it, so transparency shows palette[0].
    canvas = Image.new("RGBA", (SIZE, SIZE), palette[0] + (255,))
    img = img.resize((SIZE, SIZE), Image.LANCZOS)
    canvas.alpha_composite(img)
    rgba = list(canvas.getdata())  # 108*108 RGBA tuples

    if auto_palette:
        # Median-cut to 16 colors, ordered by frequency so index 0 stays the
        # dominant (background) color — mirroring the original palette layout.
        rgb = Image.frombytes("RGB", (SIZE, SIZE), b"".join(bytes(p[:3]) for p in rgba))
        q = rgb.quantize(colors=16, method=Image.MEDIANCUT, dither=Image.Dither.NONE)
        palette = list(q.getpalette()[:48])  # 16 RGB triples
        palette = [tuple(palette[i*3:i*3+3]) for i in range(16)]
        indexed = list(q.getdata())
    else:
        indexed = [nearest_index(p, palette) for p in rgba]

    packed = []
    for i in range(0, SIZE * SIZE, 2):
        packed.append(indexed[i] << 4 | indexed[i + 1])

    rows = []
    for start in range(0, len(packed), 18):
        chunk = packed[start:start + 18]
        rows.append("    " + ",".join(f"0x{x:02x}" for x in chunk) + ",")

    colors = ",".join(f"0x{rgb565(c):04x}" for c in palette)
    header = f"/* Generated by tools/portrait-pack.py from {png.name}. */\n"
    body = (
        f"enum {{ TRIBUTE_SIZE = {SIZE} }};\n"
        f"static const uint16_t tribute_colors[16] = {{{colors}}};\n"
        "static const uint8_t tribute_pixels[] = {\n"
        + "\n".join(rows) + "\n};\n"
    )
    out.write_text(header + body)
    print(f"wrote {out} ({len(packed)} bytes packed, 16-color palette)")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("png", type=Path)
    ap.add_argument("-o", "--output", type=Path, default=Path("board/portrait.inc"))
    ap.add_argument("--palette", help="16 RGB triples as 'r,g,b r,g,b ...' (optional)")
    ap.add_argument("--auto", action="store_true", help="derive the 16-color palette from the art")
    a = ap.parse_args()
    palette = DEFAULT_PALETTE
    if a.palette:
        parts = a.palette.split()
        if len(parts) != 16:
            sys.exit("--palette needs exactly 16 'r,g,b' triples")
        palette = [tuple(int(v) for v in p.split(",")) for p in parts]
    pack(a.png, palette, a.output, auto_palette=a.auto)

if __name__ == "__main__":
    main()
