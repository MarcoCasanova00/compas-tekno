"""Regenerate the static Sonidero rays and four rotating starburst masks."""
import math
from pathlib import Path

def pack(bits):
    return "{" + ",".join(f"0x{sum(bits[i+j]<<j for j in range(min(8,len(bits)-i))):02x}"
                         for i in range(0,len(bits),8)) + "}"

def inside(x,y,points):
    crossings=0
    for (x0,y0),(x1,y1) in zip(points,points[1:]+points[:1]):
        if (y0>y)!=(y1>y) and x<(x1-x0)*(y-y0)/(y1-y0)+x0:
            crossings+=1
    return crossings%2

rows=["/* Generated by tools/stage-art.py. LSB-first pixel masks in flash. */",
      "static const uint8_t stage_burst[4][43][6]={"]
for phase in range(4):
    points=[]
    for i in range(24):
        angle=math.radians(phase*7.5+i*15)
        radius=21*(1 if i%2==0 else 0.74)
        points.append((21+radius*math.cos(angle),21+radius*math.sin(angle)))
    rows.append("    {")
    rows.extend("        "+pack([inside(x+0.5,y+0.5,points) for x in range(43)])+"," for y in range(43))
    rows.append("    },")
rays = [[int((math.degrees(math.atan2(y-46,x-120))//15)%2==0) for x in range(240)]
        for y in range(58,188)]
runs = [[row[0], *(x for x in range(1,240) if row[x] != row[x-1]), 240] for row in rays]
rows.extend(["};", "#ifdef COMPAS_USB",
             f"static const uint8_t stage_ray_runs[130][{max(map(len, runs))}]={{"])
rows.extend("    {" + ",".join(map(str, row)) + "}," for row in runs)
rows.extend(["};", "#else", "static const uint8_t stage_rays[130][30]={"])
rows.extend("    "+pack(row)+"," for row in rays)
rows.extend(["};", "#endif"])
(Path(__file__).resolve().parents[1]/"board/stage-burst.inc").write_text("\n".join(rows)+"\n")

response = ["/* Generated by tools/stage-art.py. Q8 response at each harmonic. */",
            "static const uint16_t stage_lowpass[101][16]={"]
for tone in range(101):
    cutoff = 1.5 + 13.0 * tone / 100
    gains = []
    for harmonic in range(1, 17):
        ratio = harmonic / cutoff
        gain = 1 / math.sqrt((1 - ratio * ratio)**2 + ratio * ratio)
        gains.append(str(round(256 * gain)))
    response.append("    {" + ",".join(gains) + "},")
response.append("};")
(Path(__file__).resolve().parents[1]/"board/stage-response.inc").write_text("\n".join(response) + "\n")
